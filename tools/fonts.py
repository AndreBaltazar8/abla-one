#!/usr/bin/env python3
"""Generates Abla One's font data from Inter (SIL Open Font License):

- assets/fonts/Inter-<weight>.ttf: static instances for web-canvas pages;
- src/layout/inter_metrics.ab: advance widths (1/1000 em) for code points
  0-255 plus common punctuation, per weight, used by one-layout;
- src/raster/inter_glyphs.ab: glyph outlines for the software rasterizer
  (desktop and e-paper), when run with --glyphs.

Usage: nix-shell -p python3Packages.fonttools --run "python3 tools/fonts.py <InterVariable.ttf>"
"""
import sys, os
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

WEIGHTS = [400, 500, 600, 700]
EXTRA = [0x2014, 0x2013, 0x2026, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x20AC, 0x2192, 0x00B7]
CODES = list(range(32, 127)) + list(range(160, 256)) + EXTRA

def main():
    source = sys.argv[1]
    root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    lines = ['// Generated by tools/fonts.py from Inter (SIL Open Font License, assets/fonts/LICENSE).',
             '// Advance widths in 1/1000 em by weight; code points listed in oneInterCodes.', '']
    lines.append('val oneInterCodes = [' + ', '.join(str(c) for c in CODES) + ']')
    for weight in WEIGHTS:
        font = instantiateVariableFont(TTFont(source), {'wght': weight, 'opsz': 14} if 'opsz' in [a.axisTag for a in TTFont(source)['fvar'].axes] else {'wght': weight})
        font.save(os.path.join(root, f'assets/fonts/Inter-{weight}.ttf'))
        upem = font['head'].unitsPerEm
        cmap = font.getBestCmap()
        hmtx = font['hmtx']
        widths = []
        for code in CODES:
            glyph = cmap.get(code)
            advance = hmtx[glyph][0] if glyph else hmtx[cmap[ord('n')]][0]
            widths.append(round(advance * 1000 / upem))
        lines.append(f'val oneInterWidths{weight} = [' + ', '.join(str(w) for w in widths) + ']')
        if weight == 400:
            hhea = font['hhea']
            lines.append(f'val oneInterAscent = {round(hhea.ascent * 1000 / upem)}')
            lines.append(f'val oneInterDescent = {round(-hhea.descent * 1000 / upem)}')
    open(os.path.join(root, 'src/layout/inter_metrics.ab'), 'w').write('\n'.join(lines) + '\n')

def glyphs(source, root):
    """Outlines as int16 words, base64 per weight. Per glyph: advance,
    contour count, then per contour: point count and (x, y, on) triples with
    x/y in font units and on = 1 for on-curve points. An index maps code
    point order (oneInterCodes) to word offsets."""
    import base64, struct
    from fontTools.pens.recordingPen import DecomposingRecordingPen
    lines = ['// Generated by tools/fonts.py --glyphs from Inter (SIL Open Font License).',
             '// Outlines in font units; see tools/fonts.py for the layout.', '']
    for weight in WEIGHTS:
        font = TTFont(os.path.join(root, f'assets/fonts/Inter-{weight}.ttf'))
        upem = font['head'].unitsPerEm
        cmap = font.getBestCmap()
        glyf = font['glyf']
        hmtx = font['hmtx']
        words, index = [], []
        for code in CODES:
            index.append(len(words))
            name = cmap.get(code) or cmap[ord('?')]
            glyph = glyf[name]
            contours = []
            if glyph.numberOfContours != 0:
                coords, ends, flags = glyph.getCoordinates(glyf)
                start = 0
                for end in ends:
                    contours.append([(coords[i][0], coords[i][1], flags[i] & 1) for i in range(start, end + 1)])
                    start = end + 1
            words.append(hmtx[name][0]); words.append(len(contours))
            for contour in contours:
                words.append(len(contour))
                for x, y, on in contour: words.extend([x, y, on])
        data = base64.b64encode(struct.pack('<%dh' % len(words), *words)).decode()
        lines.append(f'val oneGlyphs{weight} = "{data}"')
        lines.append(f'val oneGlyphIndex{weight} = [' + ', '.join(map(str, index)) + ']')
    lines.append(f'val oneGlyphUnitsPerEm = {upem}')
    open(os.path.join(root, 'src/raster/inter_glyphs.ab'), 'w').write('\n'.join(lines) + '\n')

if __name__ == '__main__':
    if '--glyphs' in sys.argv:
        glyphs(sys.argv[1], os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    else:
        main()
