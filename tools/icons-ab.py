#!/usr/bin/env python3
"""Writes an Abla module embedding SVG icons, for targets with no files to read
(a microcontroller): oneEmbeddedIcon(name) gives an icon's SVG, or "".
Usage: tools/icons-ab.py OUTPUT.ab ICONS_DIR"""
import os, sys

out, icons = sys.argv[1], sys.argv[2]
def literal(text):
    return '"' + text.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$').replace('\n', '\\n') + '"'
lines = ['// Generated by tools/icons-ab.py.', 'fun oneEmbeddedIcon(name: string): string {']
for file in sorted(os.listdir(icons)):
    if file.endswith('.svg'):
        lines.append(f'    if (name == {literal(file[:-4])}) return {literal(open(os.path.join(icons, file)).read())}')
lines += ['    ""', '}', '']
open(out, 'w').write('\n'.join(lines))
