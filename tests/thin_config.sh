#!/usr/bin/env bash
# tools/papermono-thin-config: what it writes, and what it refuses. Made-up credentials, in a folder of its own.
set -euo pipefail
tool=$(cd "$(dirname "$0")/.." && pwd)/tools/papermono-thin-config
root=$(cd "$(dirname "$0")/.." && pwd)
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT
cd "$work"
failed=0
check() { if [ "$2" = "$3" ]; then echo "ok   $1"; else echo "FAIL $1"; diff <(echo "$2") <(echo "$3") || true; failed=1; fi; }
export ONE_WIFI_SSID='Rede "é"' ONE_WIFI_PASSWORD='p\w'
"$tool" --wifi
check 'the network, as bytes' "$(cat build/papermono/wifi_config.ab)" '// Generated by tools/papermono-thin-config --wifi. Holds credentials: do not commit.
fun oneWifiConfigured(): OneWifiConfig = OneWifiConfig(
    nativeStaticBytes("\x52\x65\x64\x65\x20\x22\xc3\xa9\x22\x00"), 9, nativeStaticBytes("\x70\x5c\x77\x00"), 3)'
check 'only its owner reads it' "$(stat -c %a build/papermono/wifi_config.ab)" 600
config=$root/build/papermono/thin_config.ab
saved=$work/saved
[ -e "$config" ] && mv "$config" "$saved"
restore() { rm -f "$config"; [ -e "$saved" ] && mv "$saved" "$config"; rm -rf "$work"; }
trap restore EXIT
"$tool" 10.1.2.3:8000
check 'an address and port' "$(tail -n +4 "$config")" '    nativeStaticBytes("\x52\x65\x64\x65\x20\x22\xc3\xa9\x22\x00"), 9, nativeStaticBytes("\x70\x5c\x77\x00"), 3,
    10, 1, 2, 3, 8000, false,
    nativeStaticBytes("\x31\x30\x2e\x31\x2e\x32\x2e\x33\x00"), 8, "10.1.2.3")'
"$tool" https://one.test/
check 'a name, on 443' "$(tail -n 2 "$config")" '    0, 0, 0, 0, 443, true,
    nativeStaticBytes("\x6f\x6e\x65\x2e\x74\x65\x73\x74\x00"), 8, "one.test")'
"$tool" 10.1.2.3
check 'the default port' "$(sed -n 5p "$config")" '    10, 1, 2, 3, 8954, false,'
for bad in 10.1.2 10.1.2.3.4 10.1.2.256 name:1 10.1.2.3:x; do
  if "$tool" "$bad" 2>"$work/err"; then echo "FAIL $bad taken"; failed=1
  else check "$bad refused" "$(cat "$work/err")" 'papermono-thin-config: expected HOST_IPV4[:PORT] or https://NAME[:PORT]'; fi
done
exit $failed
